// 아이디어 본문(title·description)의 품질 규칙 모음
//
// [왜 별도 파일인가]
// 이 규칙들은 "어떤 아이디어를 좋은 아이디어로 볼 것인가"에 대한 정의다.
// 씨드카드든 파생카드든 캔버스에 놓이면 똑같이 사용자가 발전시키는 재료가 되고,
// 똑같이 UX 평가(uxEval)의 대상이 되므로 판단 기준이 달라야 할 이유가 없다.
// 그런데 규칙 문장을 각 호출 파일에 따로 적어 두면, 한쪽만 다듬는 일이 반복되면서
// 씨드는 대상·상황·문제·해결이 갖춰지고 파생은 "2~3문장"만 지키는 상태로 벌어진다.
// → 아이디어 본문 품질에 관한 문장은 전부 이 파일 하나를 출처로 삼는다.
//
// [무엇이 여기 들어오지 않는가]
// - topic을 어떻게 다룰지에 대한 규칙 → prompts/topicScope.js (호출 지점마다 정책이 정반대라 분리)
// - highlightPhrases처럼 특정 호출에만 있는 출력 필드의 규칙 → 그 호출 파일에 둔다.
//   (파생 전용 필드를 공용 규칙에 섞으면 씨드 프롬프트가 존재하지 않는 필드를 설명하게 된다)
//
// 이 파일은 openaiClient.js(→ import.meta.env, Vite 전용)를 부르지 않는 순수 문자열 모듈이다.
// 그래야 Node 테스트 스크립트에서도 그대로 import할 수 있다 — 이 조건을 깨지 않을 것.
// (같은 이유로 분리한 선례: prompts/topicScope.js, prompts/toolExamplesPrompt.js)

// [표기 규칙 — 두 함수 공통]
// 반환 문자열은 대괄호 블록이 아니라 '▸ 소제목'으로 시작한다.
// 이 규칙들은 호출부(seedCard·deriveCard)가 씌우는 [작성 규칙] 블록의 하위 항목이기 때문이다.
// 대괄호로 두면 이 프롬프트에서 대괄호가 블록 구분자로 쓰이고 있어 [작성 규칙]과 형제로 읽힌다
// — 상위 블록 안에 있는데 나란한 블록으로 보이므로 계층이 사라진다.
// 기존 표기가 `[블록]`과 `- 항목` 둘뿐이라 그 사이가 비어 있어 ▸를 쓴다.
// 번호(1) 2))는 순서가 있다는 뜻이 되는데 규칙들 사이에 순서는 없다.
//
// title·description이 갖춰야 할 요소.
//
// 4가지 요소마다 "쓰지 말아야 할 표현"을 같이 적은 이유:
// "구체적으로 작성한다"만으로는 모델이 지켰는지 스스로 판정할 수 없다.
// 반면 "사람들/현대인은 쓰지 않는다"는 결과물을 보고 바로 확인할 수 있는 기준이다.
export function buildIdeaWritingRule() {
  return `▸ 아이디어 작성 규칙
- title: 한 줄로 "무엇을(서비스/기능 형태) + 누구를 위한 것인지"가 드러나야 함
- description: 2~3문장, 아래 4가지 요소를 모두 포함하여 작성한다.
  1. 대상: 특정 집단이나 계층으로 한정하여 서술한다. "사람들", "현대인"처럼 대상을 특정하지 않는 표현은 사용하지 않는다.
  2. 상황: 대상이 처한 시점·장소·상태를 구체적으로 서술한다.
  3. 문제: 그 상황에서 대상이 겪는 불편이나 장애를 구체적 사실로 서술한다. "불편하다", "어렵다" 같은 추상적 표현만으로 문제를 설명하지 않는다.
  4. 해결 방법: 문제를 해소하는 기능이나 메커니즘을 구체적으로 서술한다. "AI가 해결한다", "플랫폼으로 지원한다"처럼 주체나 방식이 불분명한 표현은 사용하지 않는다.`
}

// 해결 방법이 어디까지 나가도 되는가에 대한 기준.
//
// 마지막 항목(기관·기업 규모 전제 허용)은 앞 두 항목의 부작용을 막는 문장이다.
// "실현 가능"만 강조하면 모델이 범위를 개인 프로젝트 수준까지 좁혀 버려서
// 아이디어가 발산되지 않고 작아진다 — 제한하는 방향과 허용하는 방향을 같이 적는다.
export function buildFeasibilityRule() {
  return `▸ 실현 가능성 기준
- 해결 방법은 현재 존재하는 기술(앱, API, 센서, AI 모델 등)로 구현 설명이 가능한 범위에서 작성한다. 아직 상용화되지 않은 미래 기술이나 SF적 전제는 사용하지 않는다.
- 국가 법이나 제도 자체를 바꾸는 것을 전제로 하는 아이디어는 작성하지 않는다.
- 아이디어를 실행하는 주체가 기관·기업 규모의 데이터나 인프라, 지원을 보유하고 있다는 전제는 허용한다. 개인이 혼자 만들 수 있는 범위로 축소하지 않는다.`
}
