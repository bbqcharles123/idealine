// 사용자가 홈 화면에서 입력한 주제(topic)를 다루는 프롬프트 문장 모음
//
// [왜 별도 파일인가]
// topic은 캔버스 전체에 하나뿐인 값이지만, 이를 프롬프트에서 어떻게 다뤄야 하는지는
// 호출 지점마다 정반대다.
//   - 씨드 생성: topic은 "그대로 지켜야 할 입력 원문"이다. 대체하거나 빼면 안 된다.
//   - 파생 생성: topic은 "벗어나면 안 되는 바깥 경계"다. 내용 자체는 바뀌어도 된다.
// 두 문장을 각 파일에 흩어 두면 topic 정책을 고칠 때 한쪽만 고쳐지므로,
// topic에 관한 문장은 전부 이 파일 하나를 출처로 삼는다.
//
// 이 파일은 openaiClient.js(→ import.meta.env, Vite 전용)를 부르지 않는 순수 문자열 모듈이다.
// (같은 이유로 분리한 선례: prompts/toolExamplesPrompt.js)

// 씨드카드 본문 생성용 — 입력 원문을 얼마나 그대로 쓸 것인가에 대한 규칙.
//
// topic 문자열을 인자로 받지 않는다. 씨드 호출은 user 메시지에 이미 주제 원문을 싣고 있어서
// system 프롬프트는 "그 입력을 어떻게 다룰지"만 정하면 되기 때문이다.
export function buildTopicScopeRule() {
  return `[입력 범위 — 최우선 규칙]
사용자마다 주제에 대한 배경지식과 구체화 수준이 다르므로, 입력은 단일 키워드부터
대상·상황·문제가 이미 서술된 문장까지 다양한 형태로 들어온다.
사용자 입력에 담긴 범위를 벗어나지 않는다. 입력에 언급된 내용은 [작성 규칙]의 '아이디어 작성 규칙'
구체성 기준을 충족하지 않더라도 다른 내용으로 대체하거나 제외하지 않는다.
언급되지 않은 부분만 주제와 자연스럽게 연결되는 내용으로 새로 채운다.`
}

// 파생카드 본문 생성용 — 무엇이 경계이고 무엇이 아닌지에 대한 규칙.
//
// 파생 호출은 부모 카드의 description만 입력으로 받으므로 topic을 알 방법이 없다.
// 그래서 이 문장은 규칙인 동시에 "누락된 입력"을 채워 넣는 역할도 한다.
//
// 핵심은 "부모는 경계가 아니다"라는 한 줄이다.
// 부모 본문은 topic을 이미 한 번 좁혀서 나온 '주제 안의 한 가지 해석'인데,
// 모델이 부모만 보면 그것을 지켜야 할 범위로 착각해 부모를 거의 복제한다.
// 확장·변형은 부모를 바꾸는 것이 목적이므로, 경계는 topic 쪽에 있다고 명시해야
// 부모에서 자유롭게 멀어지면서도 주제는 벗어나지 않는다.
//
// topic이 비어 있으면(구버전 캔버스 등) 빈 문자열을 반환한다.
// 빈 주제로 만든 `""과 연결되어야 한다` 같은 문장은 기준을 주지 못하면서 있는 것처럼만 보인다.
export function buildTopicBoundaryRule(topic) {
  if (!topic) return ''
  return `[주제 경계]
이 아이디어는 사용자가 입력한 주제 "${topic}"에서 출발했다.
부모 아이디어는 이 주제 안에서 만들어진 하나의 해석일 뿐, 그 자체가 경계는 아니다.
대상·상황·문제·해결 방법은 부모와 달라져도 된다.
벗어나면 안 되는 것은 주제다. 결과물은 어떤 경우에도 "${topic}"과 연결되어야 한다.`
}
