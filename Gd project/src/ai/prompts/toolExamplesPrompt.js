// 확장하기 2단계(선택지 생성, tool_examples) 요청 사양
// — 모델에게 보낼 프롬프트 문장과 응답 스키마를 만드는 순수 함수만 둔다.
//
// [왜 deriveCard.js에서 분리했는가]
// deriveCard.js는 openaiClient.js(→ import.meta.env, Vite 전용)를 함께 불러온다.
// 그래서 Node로 실행하는 테스트 스크립트에서는 deriveCard.js를 import할 수 없고,
// 프롬프트를 테스트 쪽에 복사해 두면 나중에 한쪽만 고쳐졌을 때 조용히 어긋난다.
// (테스트가 "앱이 실제로 쓰지 않는 프롬프트"를 측정하게 되는데 겉으로는 멀쩡해 보인다)
// → 프롬프트 문장의 출처를 이 파일 하나로 만들고, 앱과 테스트가 같은 함수를 부른다.
//
// 이 파일은 브라우저 전용 API를 쓰지 않는다(순수 문자열 조립 + 정적 데이터 import).
// 그래야 Node에서도 그대로 실행된다 — 앞으로도 이 조건을 깨지 않도록 유지할 것.

// 응답 스키마 (Structured Outputs)
// 도구명 목록을 enum으로 주입해 선택지 생성 스키마를 만든다.
// toolName을 자유 문자열로 두면 모델이 '분할·분리'를 '분할/분리'처럼 살짝 다르게 써도 스키마를 통과하고,
// 화면에서 도구와 문장을 짝지을 때(find) 매칭에 실패해 빈 선택지가 된다.
// enum으로 고정하면 이름이 어긋나는 경우 자체가 사라진다. (strict 모드가 지원하는 키워드)
//
// [필드 이름을 examples/name/example에서 바꾼 이유]
// 스키마의 키 이름은 우리가 짓는 자유 이름이고, 그대로 모델에게 전달되는 지시문이기도 하다.
// 'example'은 "무엇의 예시인지"를 말해주지 않는 모호한 단어라, 모델이 완성된 해법을 설명하는
// 제안서 문장을 쓰는 쪽으로 기울었다. 이 문장의 정체는 '사용자가 읽고 고르는 선택지'이므로
// 이름 자체가 그 사실을 말하도록 바꾼다. (스키마 name 'tool_examples'는 모델에 주는 신호가
// 약하고 바꿔도 실익이 없어 그대로 둔다)
export function buildToolExamplesSchema(toolNames) {
  return {
    name: 'tool_examples',
    schema: {
      type: 'object',
      additionalProperties: false,
      required: ['options'],
      properties: {
        options: {
          type: 'array',
          description: '사용자에게 제시할 선택지 목록 — 입력된 사고도구 하나당 선택지 하나',
          items: {
            type: 'object',
            additionalProperties: false,
            required: ['toolName', 'optionText'],
            properties: {
              toolName:   { type: 'string', enum: toolNames, description: '이 선택지를 만드는 데 사용한 사고도구의 이름 (입력한 도구명 그대로)' },
              optionText: { type: 'string', description: '사용자가 모달에서 읽고 고르는 선택지 문장. 화면에는 도구 이름 없이 이 문장만 표시된다' },
            },
          },
        },
      },
    },
  }
}

// 프롬프트 조립: { system, user } 두 문자열을 만든다.
//
// cardDescription: 부모 카드 본문 (확장 모달을 연 카드의 description)
// direction:       { label, toolNames } — 1단계에서 사용자가 고른 방향성과 그 도구명들
// toolDescMap:     도구명 → 정의 문자열 맵.
//   앱은 프롬프트 전용 정의(TOOL_EXAMPLE_DESC.expand)를 넘긴다.
//   테스트 스크립트가 화면용 정의(TOOL_LAYER_DESC.expand)를 넘겨 A/B를 비교할 수 있도록
//   출처를 고정하지 않고 인자로 받는다 — 이 인자가 실험의 유일한 변수다.
export function buildToolExamplesPrompt(cardDescription, direction, toolDescMap) {
  // 도구별 정의 목록 — 도구끼리 무엇이 다른지를 알려주는 유일한 정보원이다.
  //
  // [frameworkDesc의 방향성 설명(reasoning)을 빼둔 이유]
  // 예전에는 [선택한 방향성] 아래에 그 방향성의 reasoning을 함께 넣었다.
  // 그런데 reasoning이 담은 정보는 "이 도구들이 왜 한 묶음인지"(공통점)이고,
  // 이 단계에서 모델에게 요구하는 것은 "도구끼리 서로 다르게 쓰기"(변별)다.
  // system 마지막 규칙이 "다른 도구를 대입해도 자연스러우면 실패"라고 변별을 요구하는데,
  // user가 먼저 "세 도구 모두 더하는 방향의 사고입니다" 같은 문장으로
  // 서로 바꿔 읽어도 된다는 근거를 주고 있었다 — 목적과 정반대 신호다.
  // 게다가 2방향성 reasoning은 결합을 "서로 다른 것을 연결"이라 서술해,
  // 아래 TOOL_EXAMPLE_DESC가 세운 결합(외부 자원) / 연결(무관한 두 요소)의 경계를
  // 같은 프롬프트 안에서 무너뜨렸다.
  // → 방향성은 label(사용자가 고른 문장)만 넘기고, 도구 간 차이는 정의가 전담한다.
  //
  // 정의가 없는 도구명은 이름만 남긴다 — 데이터가 어긋나도 예시 생성 자체는 막히지 않도록.
  const toolList = direction.toolNames
    .map((name) => {
      const desc = toolDescMap?.[name] ?? ''
      return desc ? `- ${name}: ${desc}` : `- ${name}`
    })
    .join('\n')

  // system: 어떤 아이디어가 들어오든 동일하게 적용되는 '작성 규칙'
  //
  // [이 문장이 쓰이는 곳] 블록을 두는 이유
  // 원래 프롬프트에는 이 문장이 어디에 어떻게 표시되는지가 한 줄도 없어서, 모델이 자기 출력을
  // '완성된 제안서'로 여기고 "~함으로써 더욱 편리한 경험을 제공합니다" 같은 문장을 썼다.
  // 네 문장이 각각 다른 문제를 겨냥한다.
  //   ① 선택지로 제시된다        → 길이 (실측 중앙값 115자 = 모달에서 약 3줄)
  //   ② 고른 문장의 도구가 다음 단계로 → 문장이 도구를 대표해야 하는 이유 (변별)
  //   ③ 도구 이름이 화면에 없다   → 라벨 없이 문장만으로 이해돼야 한다
  //                              (ExpandModal이 ModalOption에 넘기는 건 optionText 하나뿐이다)
  //   ④ 해결책이 아니라 견본이다  → 기대효과 꼬리를 붙일 이유를 없앤다
  //
  // [작성 규칙] 중 마지막 두 줄은 원래 "각 도구의 고유한 사고 방향이 예시에 분명히 드러나도록
  // 작성하세요" 한 줄이었다. '드러나도록'은 모델이 스스로 채점할 수 없는 주관적 표현이라,
  // A/B 결과에서 도구끼리 침범하는 문장이 그대로 통과했다
  // (예: '제거'가 "없애고 대신 ~를 도입"이라 써서 대체가 됨).
  // → 검사 가능한 두 단계로 바꿨다.
  //   1) 기준의 출처를 도구 정의로 고정한다 — 도구 11개의 합격 기준을 따로 쓰지 않아도 되게.
  //   2) 다른 도구로 바꿔치기가 되는지 확인시킨다 — 변별을 확인하는 절차.
  //
  // 길이는 '70자 이내'만으로는 잘 지켜지지 않는다(모델이 글자 수를 정확히 세지 못한다).
  // 대상 중심 구조 + 기대효과 배제로 문장이 짧아지게 하고, 70자는 그 안전망으로 둔다.
  // 기대효과 배제를 규칙으로 넣는 근거: 1단계처럼 도구 정의만 바꿨을 때
  // 효용어휘_포함_예시_비율이 0.345 → 0.364로 오히려 늘어, 정의 수정만으로는 잡히지 않았다.
  //
  // 이 규칙들은 보장이 아니라 유도이므로(모델이 자기 출력을 실제로 검사한다는 근거는 없다),
  // 효과는 scripts/testToolExamples.mjs로 재서 판단해야 한다.
  const system = `당신은 아이디어 발산 도구의 AI 어시스턴트입니다.
사용자가 선택한 발전 방향성에 속한 각 사고도구를, 주어진 아이디어에 실제로 적용하면 어떤 결과가 나올지 문장 하나로 작성합니다.

[이 문장이 쓰이는 곳]
작성한 문장은 사용자에게 선택지로 제시됩니다.
사용자는 문장 ${direction.toolNames.length}개를 읽고 마음에 드는 것을 하나 고르며, 고른 문장을 만드는 데 쓰인 사고도구가 다음 단계에서 그 사용자의 아이디어를 발전시키는 데 사용됩니다.
화면에는 도구 이름이 표시되지 않고 문장만 보입니다.
따라서 문장은 완성된 해결책 제안이 아니라, 그 도구로 생각하면 아이디어가 어떤 쪽으로 움직이는지 보여주는 견본입니다.

[작성 규칙]
- 입력으로 주어진 도구만, 입력된 도구명 그대로 사용하세요.
- 도구 ${direction.toolNames.length}개 전부에 대해 하나씩 빠짐없이 작성하세요. 개수가 부족하면 응답 전체가 폐기됩니다.
- optionText는 '무엇을 어떻게 조작했는가'가 문장의 중심이어야 합니다. [아이디어]에 나오는 구체적 요소 중 하나를 조작 대상으로 골라 문장에 명시하세요.
- 조작의 결과로 무엇이 좋아지는지는 쓰지 마세요. '편리해집니다', '효율적입니다', '새로운 가치를 제공합니다', '~할 수 있게 됩니다' 같은 평가 표현을 붙이지 않습니다. 조작 뒤에 무엇이 남고 무엇이 달라지는지를 사실로만 서술하는 것은 괜찮습니다.
- 한 문장으로, 70자 이내로 쓰세요.
- 각 문장은 그 도구의 정의에 적힌 조작이 문장에서 그대로 확인되어야 합니다. 정의에 등장하는 대상이 명시돼 있으면(예: "두 요소를 결합한다") 그 대상들이 문장에 모두 나와야 합니다.
- 도구 이름을 가리고 같은 목록의 다른 도구를 대입했을 때에도 문장이 자연스럽게 읽힌다면 그 문장은 실패입니다. 그 도구가 아니면 성립하지 않는 조작이 문장의 중심에 있어야 합니다.`

  const user = `[아이디어]
${cardDescription}

[선택한 방향성]
${direction.label}

[이 방향성의 도구 목록]
${toolList}

각 도구별로 이 아이디어에 적용한 선택지 문장을 작성해주세요.`

  return { system, user }
}
